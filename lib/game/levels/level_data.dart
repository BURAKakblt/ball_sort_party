import 'level.dart';

/// Difficulty bands used by the level-select screen and the level tests.
enum LevelBand {
  tutorial('Başlangıç', 1, 5),
  easy('Kolay', 6, 10),
  medium('Orta', 11, 20),
  mediumHard('Orta-Zor', 21, 35),
  hard('Zor', 36, 50);

  const LevelBand(this.label, this.first, this.last);

  final String label;
  final int first;
  final int last;

  static LevelBand of(int level) => values.firstWhere((b) => level <= b.last, orElse: () => hard);
}

